/** Les <use> d'un mot — utilisables dans un <g>, un <clipPath> ou une <mask>. */
function hero_letters(int $i, array $only = []): string
{
    $words = hero_words();
    if (!isset($words[$i])) {
        return '';
    }
    $ids = hero_glyph_ids();
    $w = $words[$i];
    $transform = sprintf('translate(%s %s) scale(%s)', $w['tx'], $w['ty'], $w['s']);
    $svg = '';
    foreach ($w['letters'] as $ch => $x) {
        if (($only && !in_array($ch, $only, true)) || !isset($ids[$ch])) {
            continue;
        }
        $svg .= sprintf(
            '<use href="#%s" transform="%s" x="%s"/>',
            $ids[$ch],
            $transform,
            $x
        );
    }
    return $svg;
}
