        $out .= '<li><a class="socials__link socials__link--' . $slug . '" href="' . htmlspecialchars($url, ENT_QUOTES) . '" target="_blank" rel="noopener noreferrer" aria-label="' . $labels[$slug] . ' (nouvel onglet)">'
             . '<svg viewBox="0 0 256 256" aria-hidden="true" focusable="false">' . $paths . '</svg></a></li>';
    }
    return $any ? $out . '</ul>' : '';
}
